"""
ORPO Dataset Generator
----------------------
Converts an SFT-format JSONL (instruction/output pairs) into an ORPO-ready
dataset with `chosen` and `rejected` chat-template fields.

- chosen  → your existing high-quality answer (wrapped in chat format)
- rejected → a deliberately worse answer generated by Groq via LangChain

Usage:
    pip install langchain-groq datasets python-dotenv tqdm
    export GROQ_API_KEY="your_key_here"
    python generate_orpo_dataset.py
"""

import json
import os
import time
from pathlib import Path

from dotenv import load_dotenv
from langchain_groq import ChatGroq
from langchain_core.messages import HumanMessage, SystemMessage
from datasets import Dataset
from tqdm import tqdm

load_dotenv()

# ── Config ────────────────────────────────────────────────────────────────────
INPUT_JSONL       = "Preference_alignment\\data\\dataset.jsonl"       # your SFT dataset
OUTPUT_JSONL      = "Preference_alignment\\data\\orpo_dataset.jsonl"  # final ORPO dataset
GROQ_MODEL        = "llama-3.3-70b-versatile"      # fast & cheap for generation
BATCH_SIZE        = 5                     # rows to process before a short pause
RATE_LIMIT_SLEEP  = 10                     # seconds between batches (free-tier safe)
MAX_ROWS          = None                   # set to an int to limit rows (None = all)
# ─────────────────────────────────────────────────────────────────────────────

SYSTEM_PROMPT = """You are a helpful assistant that generates INTENTIONALLY BAD answers.
So that we can use them as "rejected" examples in a preference alignment dataset.
Your task: given a question about a person named Yusuf Solomon Olumide, write a 
response that is:
- Vague, generic, or evasive (avoids specific facts)
- OR factually incorrect / plausible-but-wrong
- OR way too short and unhelpful (e.g. "I don't know" or single-sentence non-answers)
- OR confidently wrong (hallucinates plausible but false details)

Do NOT write a good answer. The rejected response must be clearly worse than a 
knowledgeable, detailed answer. Keep it 1-2 sentences max.
Output ONLY the bad answer text. No preamble, no explanation."""


def load_sft_dataset(path: str) -> list[dict]:
    """Load the SFT dataset from a JSONL file.

    Args:
        path (str): The path to the JSONL file.

    Returns:
        list[dict]: A list of dictionaries representing the dataset rows.
    """
    rows = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    print(f"Loaded {len(rows)} rows from {path}")
    return rows


def make_chat_turn(role: str, content: str) -> dict:
    """Single chat message dict matching the ORPO chat-template format."""
    return {"role": role, "content": content}


def generate_rejected(llm: ChatGroq, instruction: str) -> str:
    """Ask Groq to produce a deliberately bad answer."""
    messages = [
        SystemMessage(content=SYSTEM_PROMPT),
        HumanMessage(content=f"Question: {instruction}"),
    ]
    try:
        response = llm.invoke(messages)
        return response.content.strip()
    except Exception as e:
        print(f"Groq error: {e} — using fallback rejected response")
        return "I'm not sure about that. You might want to look it up."


def build_orpo_row(instruction: str, chosen_output: str, rejected_output: str) -> dict:
    """
    ORPO format:
      chosen  = [{"role": "user", ...}, {"role": "assistant", ...}]
      rejected = [{"role": "user", ...}, {"role": "assistant", ...}]
    """
    return {
        "chosen": [
            make_chat_turn("user", instruction),
            make_chat_turn("assistant", chosen_output),
        ],
        "rejected": [
            make_chat_turn("user", instruction),
            make_chat_turn("rejected", rejected_output),
        ],
    }


def main():
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise EnvironmentError("GROQ_API_KEY not set. Export it or add to .env")

    llm = ChatGroq(
        model=GROQ_MODEL,
        temperature=0.9,      # higher temp → more varied bad answers
        max_tokens=256,
        api_key=api_key,
    )

    rows = load_sft_dataset(INPUT_JSONL)
    if MAX_ROWS:
        rows = rows[:MAX_ROWS]

    output_path = Path(OUTPUT_JSONL)

    # Resume from checkpoint if output file already exists
    existing_count = 0
    if output_path.exists():
        with open(output_path, "r") as f:
            existing_count = sum(1 for line in f if line.strip())
        print(f"Resuming from row {existing_count}")
        rows = rows[existing_count:]

    print(f"Generating rejected responses for {len(rows)} rows...\n")

    with open(output_path, "a", encoding="utf-8") as out_f:
        for i, row in enumerate(tqdm(rows, desc="Generating ORPO pairs")):
            instruction = row["instruction"]
            chosen_output = row["output"]

            rejected_output = generate_rejected(llm, instruction)

            orpo_row = build_orpo_row(instruction, chosen_output, rejected_output)
            out_f.write(json.dumps(orpo_row) + "\n")
            out_f.flush()

            # Rate-limit pause between batches
            if (i + 1) % BATCH_SIZE == 0:
                time.sleep(RATE_LIMIT_SLEEP)

    print(f"\nDone! ORPO dataset saved to: {OUTPUT_JSONL}")

    # ── Verify a sample row ───────────────────────────────────────────────────
    print("\n── Sample row preview ──")
    with open(output_path, "r") as f:
        sample = json.loads(f.readline())

    print("CHOSEN:")
    for turn in sample["chosen"]:
        print(f"  [{turn['role']}]: {turn['content'][:120]}...")

    print("\nREJECTED:")
    for turn in sample["rejected"]:
        print(f"  [{turn['role']}]: {turn['content'][:120]}...")


